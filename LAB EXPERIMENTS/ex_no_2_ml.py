# Candidate-Elimination Algorithm

import csv

with open("training.csv", "r") as file:
    data = list(csv.reader(file))

attributes = data[0][:-1]
examples = data[1:]

n = len(attributes)
S = ['0'] * n
G = [['?'] * n]

for row in examples:
    x = row[:-1]
    label = row[-1]

    if label == 'Yes':
        G = [g for g in G if all(
            g[i] == '?' or g[i] == x[i] for i in range(n)
        )]

        for i in range(n):
            if S[i] == '0':
                S[i] = x[i]
            elif S[i] != x[i]:
                S[i] = '?'

    else:
        new_G = []
        for g in G:
            for i in range(n):
                if g[i] == '?' and S[i] != '?' and S[i] != '0':
                    if S[i] != x[i]:
                        h = g.copy()
                        h[i] = S[i]
                        new_G.append(h)
        G = new_G

print("Specific Boundary S:", S)
print("General Boundary G:", G)